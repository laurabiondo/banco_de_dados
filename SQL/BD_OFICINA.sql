SELECT 
    CLIENTES.NOME,
    COUNT(VEICULOS.ID) AS QUANTIDADE_CARROS
FROM CLIENTES
LEFT JOIN VEICULOS
ON CLIENTES.ID = VEICULOS.FK_CLIENTES_ID
GROUP BY CLIENTES.ID, CLIENTES.NOME;

SELECT 
    VEICULOS.PLACA,
    VEICULOS.MARCA,
    VEICULOS.MODELO,
    COUNT(AGENDAMENTOS.ID) AS QUANTIDADE_AGENDAMENTOS
FROM VEICULOS
LEFT JOIN AGENDAMENTOS
ON VEICULOS.ID = AGENDAMENTOS.FK_VEICULOS_ID
GROUP BY VEICULOS.ID, VEICULOS.PLACA, VEICULOS.MARCA, VEICULOS.MODELO;

SELECT 
    CLIENTES.NOME,
    COUNT(AGENDAMENTOS.ID) AS QUANTIDADE_AGENDAMENTOS
FROM CLIENTES
LEFT JOIN VEICULOS
ON CLIENTES.ID = VEICULOS.FK_CLIENTES_ID
LEFT JOIN AGENDAMENTOS
ON VEICULOS.ID = AGENDAMENTOS.FK_VEICULOS_ID
GROUP BY CLIENTES.ID, CLIENTES.NOME;