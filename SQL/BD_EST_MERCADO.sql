CREATE DATABASE IF NOT EXISTS BD_EST_SUPER;
USE BD_EST_SUPER;

CREATE TABLE IF NOT EXISTS CATEGORIA(
	ID INT AUTO_INCREMENT PRIMARY KEY,
    TIPO_PRODUTO VARCHAR(100) NOT NULL, 
    NOME VARCHAR(255) NOT NULL
);
CREATE TABLE IF NOT EXISTS FORNECEDOR(
	CPF VARCHAR(11) PRIMARY KEY,
    NOME VARCHAR(255) NOT NULL,
    TELEFONE INT NOT NULL
);
CREATE TABLE IF NOT EXISTS PRODUTO(
	CODIGO INT PRIMARY KEY,
    NOME VARCHAR(255) NOT NULL,
    DATA_VALIDADE DATE,
    FK_CATEGORIA_ID INT,
    FOREIGN KEY (FK_CATEGORIA_ID) REFERENCES CATEGORIA(ID)
);
CREATE TABLE IF NOT EXISTS PRODUTO_FORNECEDOR(
	ID INT AUTO_INCREMENT PRIMARY KEY,
    FK_PRODUTO_CODIGO INT,
    FK_FORNECEDOR_CPF VARCHAR(11),
    FOREIGN KEY (FK_PRODUTO_CODIGO) REFERENCES PRODUTO(CODIGO),
    FOREIGN KEY (FK_FORNECEDOR_CPF) REFERENCES FORNECEDOR(CPF)
);